"""Regenerate registry/books.md, the human-readable table of the books and their units.

Run from the repository root: python3 scripts/generate_registry.py
"""

import json
from pathlib import Path

HEADER = """# CBTUDR: books

Generated by `scripts/generate_registry.py` from `data/`. Do not edit by hand.

- **Units**: textual units that are not split (a split unit counts as its parts).
- **Without NV text**: units whose verse number the Nova Vulgata prints in brackets, without text.
- **Splits**: units divided into parts.

| # | Segment | OSIS | Nova Vulgata | English | Units | Without NV text | Splits | Mapped editions |
|---|---|---|---|---|---|---|---|---|
"""


def book_rows(books, units, maps):
    rows = []
    for b in books:
        us = units[b["segment"]]["units"]
        parents = {u["parent"] for u in us if "parent" in u}
        leaves = [u for u in us if u["id"] not in parents]
        omitted = sum(1 for u in us if u.get("nv_omitted"))
        eds = ", ".join(sorted(maps.get(b["segment"], [])))
        rows.append(f"| {b['number']} | `{b['segment']}` | `{b['osis']}` | {b['label_la']} | {b['label_en']} | {len(leaves)} | {omitted} | {len(parents)} | {eds} |")
    return rows


def main():
    root = Path(__file__).resolve().parent.parent
    books = json.loads((root / "data/books.json").read_text())["books"]
    units = {b["segment"]: json.loads((root / f"data/units/{b['number']:02d}-{b['segment']}.json").read_text()) for b in books}
    maps = {}
    for ed in json.loads((root / "data/editions.json").read_text())["editions"]:
        for path in (root / f"data/maps/{ed['slug']}").glob("*.json"):
            maps.setdefault(json.loads(path.read_text())["book"], []).append(ed["slug"])
    (root / "registry/books.md").write_text(HEADER + "\n".join(book_rows(books, units, maps)) + "\n")


if __name__ == "__main__":
    main()
